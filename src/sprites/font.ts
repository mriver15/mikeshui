/** Pixel width of `text` at `scale`, with one (scaled) pixel between letters. Unknown characters are skipped. */
export function textWidth(text: string, scale = 1, font: Font = SMALL_FONT): number {
  let w = 0;
  for (const ch of text) {
    const g = font[ch];
    if (g) w += (g[0].length + 1) * scale;
  }
  return Math.max(0, w - scale);
}

/** Draw `text` centred on `cx` with its top at `y`. */
export function drawText(p: Pixmap, text: string, cx: number, y: number, color: number, scale = 1, font: Font = SMALL_FONT): void {
  let x = Math.round(cx - textWidth(text, scale, font) / 2);
  for (const ch of text) {
    const g = font[ch];
    if (!g) continue;
    g.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) {
        if (row[rx] === "1") p.fillRect(x + rx * scale, y + ry * scale, scale, scale, color);
      }
    });
    x += (g[0].length + 1) * scale;
  }
}
